// Regenerates lib/guideFontData.ts from three OFL Google Fonts.
//
//   node scripts/embed-guide-fonts.mjs <dir containing the .ttf files>
//
// The layout guide is rasterised by sharp on Vercel, where the runtime has no
// fonts at all: every <text> came out as a row of empty boxes, and the render
// copied the boxes onto the backdrop (2026-10-20). The guide now draws
// lettering as paths built from these embedded fonts instead.
//
// Sources (SIL Open Font License), from github.com/google/fonts:
//   ofl/sacramento/Sacramento-Regular.ttf          -> script
//     (2026-10-22: was Dancing Script; the customer's reference lettering is
//     a thin, slanted, handwritten signature script)
//   ofl/archivoblack/ArchivoBlack-Regular.ttf      -> block
//   ofl/playfairdisplay/PlayfairDisplay[wght].ttf  -> elegant
import fs from "node:fs";
import path from "node:path";

const dir = process.argv[2];
if (!dir) { console.error("usage: node scripts/embed-guide-fonts.mjs <font dir>"); process.exit(1); }
const files = { script: "Sacramento.ttf", block: "ArchivoBlack.ttf", elegant: "PlayfairDisplay.ttf" };
const lines = [
  "// GENERATED by scripts/embed-guide-fonts.mjs — do not edit by hand.",
  "// Sacramento, Archivo Black and Playfair Display, SIL Open Font License.",
  "export const GUIDE_FONT_DATA: Record<\"script\" | \"block\" | \"elegant\", string> = {",
];
for (const [key, file] of Object.entries(files)) {
  const b64 = fs.readFileSync(path.join(dir, file)).toString("base64");
  lines.push(`  ${key}: "${b64}",`);
  console.log(key, file, b64.length);
}
lines.push("};", "");
fs.writeFileSync(new URL("../lib/guideFontData.ts", import.meta.url), lines.join("\n"));
